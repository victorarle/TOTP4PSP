// Generates digits.h: the digits 0-9 and "-" of Source Sans Pro Bold, rasterized with
// antialiasing at the exact pixel sizes the screen uses, as 4-bit PSP textures.
//
//   swift tools/gen_digits.swift /path/to/SourceSansPro-Bold.otf > digits.h
//
// intraFont only has the PSP's small bitmap fonts; scaled up for the large code they turn
// blurry. These glyphs are drawn 1:1 instead. macOS only (CoreText).
// Source Sans Pro: Copyright 2010, 2012 Adobe Systems Incorporated, SIL Open Font License 1.1.
import CoreGraphics
import CoreText
import Foundation

let chars = Array("0123456789-")

// name, font size in px: LARGE for the selected code, SMALL for the neighbours and the ring
let sizes: [(String, CGFloat)] = [("LARGE", 56), ("SMALL", 22)]

func pow2(_ n: Int) -> Int { var p = 1; while p < n { p *= 2 }; return p }

guard CommandLine.arguments.count == 2,
      let descs = CTFontManagerCreateFontDescriptorsFromURL(URL(fileURLWithPath: CommandLine.arguments[1]) as CFURL) as? [CTFontDescriptor],
      let desc = descs.first
else {
    FileHandle.standardError.write("usage: swift gen_digits.swift SourceSansPro-Bold.otf\n".data(using: .utf8)!)
    exit(1)
}

print("// Generated by tools/gen_digits.swift from \(URL(fileURLWithPath: CommandLine.arguments[1]).lastPathComponent); do not edit.")
print("// Glyphs of Source Sans Pro Bold, Copyright 2010, 2012 Adobe Systems Incorporated, SIL Open Font License 1.1.")
print("// Each set is a row of equal cells, one per character of DIGITS_CHARS, 4 bits per pixel")
print("// (coverage, even x in the low nibble), STRIDE pixels a row. Only the CELL_H rows in use are")
print("// stored: TEX_W x TEX_H is the power-of-two size to give sceGuTexImage.")
print("#define DIGITS_CHARS \"\(String(chars))\"")

for (name, size) in sizes {
    let font = CTFontCreateWithFontDescriptor(desc, size, nil)
    var unichars = chars.map { UniChar($0.unicodeScalars.first!.value) }
    var glyphs = [CGGlyph](repeating: 0, count: chars.count)
    CTFontGetGlyphsForCharacters(font, &unichars, &glyphs, chars.count)
    var advances = [CGSize](repeating: .zero, count: chars.count)
    CTFontGetAdvancesForGlyphs(font, .horizontal, glyphs, &advances, chars.count)
    var rects = [CGRect](repeating: .zero, count: chars.count)
    let all = CTFontGetBoundingRectsForGlyphs(font, .horizontal, glyphs, &rects, chars.count)

    // Tabular cells: as wide as the widest digit, as tall as all glyphs plus 1 px for antialiasing
    let cellW = Int(ceil(advances.prefix(10).map { $0.width }.max()!))
    let baseline = 1 - Int(floor(all.minY))               // from the bottom of the cell
    let cellH = baseline + Int(ceil(all.maxY)) + 1
    let digitTop = rects.prefix(10).map { $0.maxY }.max()!   // height of the digits above the baseline
    let texW = pow2(cellW * chars.count), texH = pow2(cellH)
    let rowW = (cellW * chars.count + 31) / 32 * 32   // a row of a 4-bit texture is a multiple of 16 bytes

    let ctx = CGContext(data: nil, width: rowW, height: cellH, bitsPerComponent: 8, bytesPerRow: rowW,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setAllowsFontSmoothing(false)
    ctx.setShouldSubpixelPositionFonts(false)
    ctx.setFillColor(gray: 0, alpha: 1)
    ctx.fill(CGRect(x: 0, y: 0, width: rowW, height: cellH))
    ctx.setFillColor(gray: 1, alpha: 1)
    // CoreGraphics counts y from the bottom
    var positions = (0..<chars.count).map { i in
        CGPoint(x: CGFloat(i * cellW) + ((CGFloat(cellW) - advances[i].width) / 2).rounded(), y: CGFloat(baseline))
    }
    CTFontDrawGlyphs(font, glyphs, &positions, chars.count, ctx)

    let px = ctx.data!.assumingMemoryBound(to: UInt8.self)
    var bytes = [UInt8](repeating: 0, count: rowW * cellH / 2)
    for y in 0..<cellH {
        for x in 0..<rowW {
            let v = UInt8((Int(px[y * rowW + x]) * 15 + 127) / 255)
            bytes[(y * rowW + x) / 2] |= (x & 1) == 1 ? v << 4 : v
        }
    }

    print("")
    print("#define DIGITS_\(name)_CELL_W \(cellW)")
    print("#define DIGITS_\(name)_CELL_H \(cellH)")
    print("#define DIGITS_\(name)_BASELINE \(cellH - baseline)   // from the top of the cell")
    print("#define DIGITS_\(name)_HEIGHT \(Int(digitTop.rounded()))   // of a digit, above the baseline")
    print("#define DIGITS_\(name)_TEX_W \(texW)")
    print("#define DIGITS_\(name)_TEX_H \(texH)")
    print("#define DIGITS_\(name)_STRIDE \(rowW)")
    print("static const unsigned char __attribute__((aligned(16))) digits_\(name.lowercased())[\(bytes.count)] = {")
    for row in stride(from: 0, to: bytes.count, by: 32) {
        print("    " + bytes[row..<min(row + 32, bytes.count)].map { String(format: "0x%02x,", $0) }.joined())
    }
    print("};")
}
